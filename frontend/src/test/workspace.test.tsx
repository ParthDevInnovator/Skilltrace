import { beforeEach, describe, expect, it, vi } from 'vitest'
import { render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from '@/App'
import { api } from '@/services/api'
vi.mock('@/services/api', () => ({ api: { getJobs: vi.fn(), getCandidates: vi.fn(), getCandidateById: vi.fn(), getCandidateContext: vi.fn(), getCandidateResume: vi.fn() } }))
const jobs = [{ id: 'JOB-001', title: 'Backend Engineer', department: 'Engineering', location: 'Remote', description_raw: 'Build services', requirements_preview: ['Python'], created_at: '2026-10-26' }, { id: 'JOB-002', title: 'Frontend Engineer', department: 'Product', location: 'London', description_raw: 'Build interfaces', requirements_preview: ['React'], created_at: '2026-10-26' }]
const candidate = { id: 'CAND-001', full_name: 'Alex Chen', email: 'alex@example.com', headline: 'Backend Engineer', location: 'Remote', top_skills: ['Python'], claims_preview: ['Built reliable APIs'], summary: 'Experienced API developer' }
beforeEach(() => { vi.resetAllMocks(); vi.mocked(api.getCandidateContext).mockResolvedValue({ candidate_id: candidate.id, status: 'building' }); vi.mocked(api.getJobs).mockResolvedValue(jobs); vi.mocked(api.getCandidates).mockResolvedValue([candidate]); vi.mocked(api.getCandidateById).mockResolvedValue(candidate) })
describe('Phase 1 workspace', () => {
  it('filters jobs by ID, clears selection, and renders distinct pages', async () => {
    const user = userEvent.setup(); render(<App />)
    await user.click(await screen.findByRole('button', { name: /Backend Engineer/ }))
    await user.type(screen.getByLabelText('Find a job'), 'job-002')
    const picker = screen.getByRole('region', { name: 'Choose active job' })
    expect(within(picker).queryByRole('button', { name: /Backend Engineer/ })).not.toBeInTheDocument()
    await user.click(within(picker).getByRole('button', { name: /Frontend Engineer/ }))
    expect(screen.getByRole('heading', { name: 'Frontend Engineer' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /Frontend Engineer/ }))
    await user.click(screen.getByRole('button', { name: 'Clear selection' }))
    expect(screen.getByText('Select a job in the header or create a custom requisition.')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Jobs' }))
    expect(screen.getByRole('heading', { name: 'Jobs' })).toBeInTheDocument()
    expect(screen.queryByRole('heading', { name: 'Candidate Pool' })).not.toBeInTheDocument()
  })
  it('validates a custom job, accepts location, and restores focus on Escape', async () => {
    const user = userEvent.setup(); render(<App />)
    await user.click(screen.getByRole('button', { name: 'Create Job' }))
    expect(screen.getByLabelText('Job Title *')).toHaveFocus()
    await user.click(screen.getByRole('button', { name: 'Set as Active Requisition' }))
    expect(screen.getByRole('alert')).toHaveTextContent('provide a job title')
    await user.type(screen.getByLabelText('Job Title *'), 'Custom Architect')
    await user.type(screen.getByLabelText('Job Description Text *'), 'Short')
    await user.click(screen.getByRole('button', { name: 'Set as Active Requisition' }))
    expect(screen.getByRole('alert')).toHaveTextContent('50 characters')
    await user.clear(screen.getByLabelText('Job Description Text *'))
    await user.type(screen.getByLabelText('Job Description Text *'), 'Design reliable Python services and maintain distributed infrastructure with Kubernetes.')
    await user.clear(screen.getByLabelText('Location')); await user.type(screen.getByLabelText('Location'), 'Pune')
    await user.click(screen.getByRole('button', { name: 'Set as Active Requisition' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Custom Architect' })).toBeInTheDocument()
    expect(screen.getByText('Engineering - Pune')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Create Job' })); await user.keyboard('{Escape}')
    expect(screen.getByRole('button', { name: 'Create Job' })).toHaveFocus()
  })
  it('filters candidates, resets, opens tabs and retains the selected job', async () => {
    const user = userEvent.setup(); render(<App />)
    await user.click(await screen.findByRole('button', { name: 'View Profile' }))
    await user.click(await screen.findByRole('button', { name: /Reported Skills/ }))
    expect(screen.getByText('Core Technical Competencies')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Background Summary' }))
    expect(screen.getByText('Experienced API developer')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Back to Recruiter Overview' }))
    expect(screen.getByRole('heading', { name: 'Backend Engineer' })).toBeInTheDocument()
    await user.type(screen.getByLabelText('Search candidates'), 'alex')
    await waitFor(() => expect(api.getCandidates).toHaveBeenLastCalledWith({ search: 'alex', skill: undefined }))
    await user.click(screen.getByRole('button', { name: 'Python' }))
    await waitFor(() => expect(api.getCandidates).toHaveBeenLastCalledWith({ search: 'alex', skill: 'Python' }))
    await user.click(screen.getByRole('button', { name: 'Reset Filters' }))
    expect(screen.getByLabelText('Search candidates')).toHaveValue('')
    await waitFor(() => expect(api.getCandidates).toHaveBeenLastCalledWith({ search: undefined, skill: undefined }))
  })
  it('shows fetch failures, retries jobs, and shows empty candidates', async () => {
    vi.mocked(api.getJobs).mockRejectedValueOnce(new Error('offline'))
    vi.mocked(api.getCandidates).mockResolvedValue([])
    const user = userEvent.setup(); render(<App />)
    expect(await screen.findByRole('alert')).toHaveTextContent('Failed to load jobs')
    await user.click(screen.getByRole('button', { name: 'Retry jobs' }))
    expect(await screen.findByRole('heading', { name: 'Backend Engineer' })).toBeInTheDocument()
    expect(await screen.findByText('No Candidates Found')).toBeInTheDocument()
  })
  it('shows candidate failure and unassessed scores without inventing a match', async () => {
    vi.mocked(api.getCandidates).mockRejectedValue(new Error('offline'))
    render(<App />)
    expect(await screen.findByText('Failed to fetch candidates from server.')).toBeInTheDocument()
    expect(screen.queryByText('60% Match')).not.toBeInTheDocument()
  })
})
