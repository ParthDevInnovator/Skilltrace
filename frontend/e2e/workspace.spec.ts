test('uploads real text, PDF and DOCX documents and rejects invalid files', async ({ page }) => {
  await page.goto('/'); await page.getByRole('button', { name: 'Create Job' }).click()
  await page.getByRole('button', { name: 'Upload Document' }).click()
  const input = page.getByLabel('Drop a job description here or browse files')
  await input.setInputFiles({ name: 'role.exe', mimeType: 'application/octet-stream', buffer: Buffer.from('invalid') })
  await expect(page.getByRole('alert')).toContainText('TXT, MD, PDF or DOCX')
  await input.setInputFiles({ name: 'empty.txt', mimeType: 'text/plain', buffer: Buffer.alloc(0) })
  await expect(page.getByRole('alert')).toContainText('empty')
  await input.setInputFiles({ name: 'large.txt', mimeType: 'text/plain', buffer: Buffer.alloc(5 * 1024 * 1024 + 1, 'a') })
  await expect(page.getByRole('alert')).toContainText('5 MB')
  const transfer = await page.evaluateHandle(() => {
    const data = new DataTransfer()
    data.items.add(new File(['Build reliable Python services with Kubernetes, FastAPI and PostgreSQL for production customers.'], 'dropped.txt', { type: 'text/plain' }))
    return data
  })
  await page.locator('.drop-zone').dispatchEvent('drop', { dataTransfer: transfer })
  await expect(page.getByRole('dialog').getByRole('status')).toContainText('Loaded: dropped.txt')
  for (const filename of ['role.txt', 'role.pdf', 'role.docx']) {
    await input.setInputFiles(path.join(import.meta.dirname, 'fixtures', filename))
    await expect(page.getByRole('dialog').getByRole('status')).toContainText(`Loaded: ${filename}`, { timeout: 20000 })
    await expect(page.getByLabel('Job Description Text *')).toHaveValue(/Build reliable Python/)
  }
  await page.getByRole('button', { name: 'Set as Active Requisition' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
test('job failure, retry and clear selection are visible', async ({ page }) => {
  await page.route('**/api/v1/jobs', route => route.fulfill({ status: 503, json: {} }))
  await page.goto('/'); await expect(page.getByRole('alert')).toContainText('Failed to load jobs')
  await page.route('**/api/v1/jobs', route => route.fulfill({ json: jobs }))
  await page.getByRole('button', { name: 'Retry jobs' }).click()
  await expect(page.getByRole('heading', { name: jobs[0].title })).toBeVisible()
  await page.getByRole('button', { name: jobs[0].title }).click()
  await page.getByLabel('Find a job').fill('JOB-002')
  await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: jobs[1].title })).toBeVisible()
  await page.getByRole('button', { name: jobs[1].title }).click()
  await page.getByRole('button', { name: 'Clear selection' }).click()
  await expect(page.getByText('Select a job in the header or create a custom requisition.')).toBeVisible()
})

test('workspace accessibility and narrow profile layout', async ({ page }, info) => {
  test.setTimeout(60000)
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'View Profile' })).toHaveCount(6)
  const scan = async () => {
    const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(results.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, summary: n.failureSummary })) }))).toEqual([])
  }
  await scan()
  await page.getByRole('button', { name: 'Jobs', exact: true }).click(); await scan()
  await page.getByRole('button', { name: jobs[0].title }).click(); await scan()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Overview', exact: true }).click()
  await page.getByRole('button', { name: 'Create Job' }).click(); await scan()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'View Profile' }).first().click()
  await expect(page.getByRole('heading', { name: 'Alex Rivera' })).toBeVisible()
  await scan()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: `test-results/${info.project.name}-profile.png`, fullPage: true })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  expect(await page.evaluate(() => matchMedia('(prefers-reduced-motion: reduce)').matches)).toBe(true)
})
